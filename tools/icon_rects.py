#!/usr/bin/env python3
"""Writes src/client/IconRects.luau: each slot icon's drawn area (alpha > 40) in its image.

Slots crop an icon to its drawn area (ImageRectOffset/ImageRectSize) and fit it in a
square box centred on the slot, so every icon sits centred with even padding whatever
margin its source image has (docs/ui/inventory.md, "Icon padding").
Covered: every image under art/ui/icons and art/ui/glyphs in art/ui/assets.json, plus
the icons Items/Techniques/SlotArt reference. Images with no local file (the first five
technique icons) were measured in Studio with EditableImage; they are listed in STUDIO.
Run after adding or redrawing an icon:  uv run --with pillow python tools/icon_rects.py
"""
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "art/ui"
OUT = ROOT / "src/client/IconRects.luau"
ALPHA = 40

# id -> (x, y, w, h) measured in Studio (AssetService:CreateEditableImageAsync)
STUDIO = {
    "100918699109239": (32, 32, 203, 203),  # Sword Qi Wave
    "98382420618802": (23, 32, 191, 178),  # Palm Strike
    "89161711966835": (74, 15, 108, 226),  # Lightning Talisman
    "73960875385866": (38, 30, 180, 213),  # Iron Skin
    "123372008874762": (11, 11, 234, 234),  # Fire Seal
}


def bbox(path):
    im = Image.open(path).convert("RGBA")
    box = im.getchannel("A").point(lambda v: 255 if v > ALPHA else 0).getbbox()
    if not box:
        return None
    x0, y0, x1, y1 = box
    return (x0, y0, x1 - x0, y1 - y0)


def main():
    assets = json.loads((ART / "assets.json").read_text())
    by_id = {}
    for name, uri in assets.items():
        by_id.setdefault(uri.removeprefix("rbxassetid://"), name)
    wanted = {}
    for name, uri in assets.items():
        if name.startswith(("icons/", "glyphs/")):
            wanted[uri.removeprefix("rbxassetid://")] = name
    for src in ["src/shared/Items.luau", "src/shared/Techniques.luau", "src/client/SlotArt.luau"]:
        for m in re.finditer(r"rbxassetid://(\d+)", (ROOT / src).read_text()):
            wanted.setdefault(m.group(1), by_id.get(m.group(1), ""))
    rows = []
    for asset_id in sorted(wanted):
        name = wanted[asset_id]
        rect = None
        if name and (ART / name).exists():
            rect = bbox(ART / name)
        elif asset_id in STUDIO:
            rect = STUDIO[asset_id]
        if rect:
            rows.append(f'\t["{asset_id}"] = {{ {rect[0]}, {rect[1]}, {rect[2]}, {rect[3]} }}, -- {name or "studio"}')
        else:
            print("no rect for", asset_id, name)
    OUT.write_text(
        "--!strict\n"
        "-- Generated by tools/icon_rects.py; don't edit by hand. Each slot icon's drawn area\n"
        "-- (x, y, w, h; alpha > 40) in its source image, by asset id. SlotArt.setIcon crops to\n"
        "-- it so icons centre on their slot with even padding.\n\n"
        "return {\n" + "\n".join(rows) + "\n} :: { [string]: { number } }\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} icons)")


if __name__ == "__main__":
    main()
