"""Builds tools/vfx_session.luau: one paste for execute_luau that installs every
Edit-mode VFX helper (each tool file runs in its own function, so their locals
don't collide) and returns what was installed. The tool files stay the source
of truth; re-run this after editing any of them:  python3 tools/build_vfx_session.py
"""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = [
    "export_rbxm.luau",  # _G.exportRbxm
    "vfx_library.luau",  # _G.vfxLibrary
    "anim_markers.luau",  # _G.animMarkers
    "vfx_preview.luau",  # _G.vfxPreview (scene, castThrough, sweep)
    "vfx_stage.luau",  # _G.vfxStage (begin/finish)
    "vfx_diff.luau",  # _G.vfxDiff (structural template diff)
    "vfx_blocks.luau",  # _G.vfxBlocks (template builders, buildFromSpec)
]


def main():
    parts = [
        "--!nocheck",
        "-- GENERATED by tools/build_vfx_session.py from the tool files listed below;",
        "-- edit those, then re-run the script. Paste this whole file into execute_luau",
        "-- once per Studio session (Edit mode). Returns one line per installed helper.",
        "local installed = {}",
    ]
    for name in TOOLS:
        path = os.path.join(HERE, name)
        if not os.path.exists(path):
            continue
        src = open(path).read().rstrip()
        parts += [
            f"do -- {name}",
            "\tlocal ok, msg = pcall(function()",
            src,
            "\tend)",
            f'\ttable.insert(installed, "{name}: " .. tostring(msg))',
            "end",
        ]
    specs = sorted(glob.glob(os.path.join(HERE, "vfx_specs", "*.luau")))
    if specs:
        parts.append("_G.vfxSpecs = _G.vfxSpecs or {}")
    for path in specs:
        id_ = os.path.basename(path)[:-5]
        src = open(path).read().rstrip()
        parts += [
            f"do -- vfx_specs/{id_}.luau",
            "\tlocal ok, spec = pcall(function()",
            src,
            "\tend)",
            f'\tif ok then _G.vfxSpecs["{id_}"] = spec end',
            f'\ttable.insert(installed, "spec {id_}: " .. (ok and "ok" or tostring(spec)))',
            "end",
        ]
    parts.append('return table.concat(installed, "\\n")')
    out = os.path.join(HERE, "vfx_session.luau")
    open(out, "w").write("\n".join(parts) + "\n")
    print(out, sum(1 for _ in open(out)), "lines")


if __name__ == "__main__":
    main()
